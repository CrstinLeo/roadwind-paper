"""Numbers and tables of the manuscript, written to <repo>/sections/generated/.

numbers.tex   \\newcommand macros for every number quoted in the text
tab_ladder.tex, tab_coefs.tex, tab_variants.tex
Run after 04/06/07/08 and 09 so that text, tables and figures come from the same run.
"""
import os
import pickle
from pathlib import Path

import numpy as np
import pandas as pd

from smhi_trv_wind import Settings, evaluate
from smhi_trv_wind.data import smhi as sd
from smhi_trv_wind.features.gis import sector_tables
from smhi_trv_wind.model import physics, site_factors as sfm

cfg = Settings()
OUT = cfg.paths.out
GEN = Path(os.environ.get("SWW_GEN", Path(__file__).resolve().parents[2] / "sections" / "generated"))
GEN.mkdir(parents=True, exist_ok=True)
R = pickle.load(open(OUT / "result.pkl", "rb"))
CV = pickle.load(open(OUT / "cv_full.pkl", "rb"))
CAND = pickle.load(open(OUT / "candidates_cv.pkl", "rb"))["res"]


def paired(a, b):
    d = a - b
    ok = np.isfinite(d)
    return d[ok].mean(), d[ok].std(ddof=1) / np.sqrt(ok.sum())


N = {}
H = cfg.hours
N["nHours"] = len(H)
N["periodStart"] = f"{H[0]:%Y-%m-%d %H:%M}"
N["periodEnd"] = f"{H[-1]:%Y-%m-%d %H:%M}"
N["nTrv"] = R.trv.shape[0]
N["nSmhi"] = R.smhi.shape[0]
N["nPairsEighty"] = int((R.P.dist <= 80).sum())
N["nSiteHours"] = R.site.hours
lad = evaluate.ladder(R.P)
for i, k in enumerate(["Raw", "Height", "Rough", "Site", "Expo"]):
    N[f"lad{k}Mae"] = f"{lad.mae.iloc[i]:.2f}"
    N[f"lad{k}Bias"] = f"{100 * lad.bias.iloc[i]:+.0f}"
c, c0 = CV["cv"], CV["cv0"]
d, se = paired(c["mae"], c0["mae"])
N.update(cvFinalMean=f"{np.nanmean(c['mae']):.2f}", cvFinalMed=f"{np.nanmedian(c['mae']):.2f}",
         cvSixMean=f"{np.nanmean(c0['mae']):.2f}", cvSixMed=f"{np.nanmedian(c0['mae']):.2f}",
         cvDiff=f"{d:.3f}", cvDiffSE=f"{se:.3f}", cvRawMed=f"{np.nanmedian(c['mae_raw']):.2f}", cvRawMean=f"{np.nanmean(c['mae_raw']):.2f}",
         cvDir=f"{np.nanmedian(c['dir']):.1f}", cvDirRaw=f"{np.nanmedian(c['dir_raw']):.1f}",
         cvBetter=int(np.sum(c["mae"] < c["mae_raw"])), cvBias=f"{100 * (np.exp(np.nanmedian(c['bias_log'])) - 1):.0f}",
         cvReduction=f"{100 * (1 - np.nanmedian(c['mae']) / np.nanmedian(c['mae_raw'])):.0f}")
raw, pot = np.exp(R.site_raw.c.mean(1)), np.exp(R.site.c.mean(1))
names = R.smhi.name
N.update(sfRawMin=f"{raw.min():.2f}", sfRawMax=f"{raw.max():.2f}", sfRawMinName=names[raw.idxmin()], sfRawMaxName=names[raw.idxmax()],
         sfPotMin=f"{pot.min():.2f}", sfPotMax=f"{pot.max():.2f}",
         sfPhysShare=f"{100 * (1 - R.site.c.mean(1).var() / R.site_raw.c.mean(1).var()):.0f}")
tabs = sector_tables(cfg)
wsL, wdL = sd.history(cfg)
potL, _ = physics.potential_wind(wsL, wdL, tabs["z0_smhi"], cfg)
N["sfStability"] = f"{sfm.stability(potL, wdL, cfg):.2f}"
SM = sd.stations(cfg)
geo = pd.DataFrame([dict(id=s, dir=k, tree=tabs["tree_smhi"].loc[s, k], ln_z0_1km=np.log(tabs["z0_smhi_1km"].loc[s, k]),
                         ln1p_coast=np.log1p(tabs["coast_smhi"].get(s, np.nan)), elev_100m=SM.loc[s, "masl"] / 100)
                    for s in R.site_raw.c.index for k in R.site_raw.c.columns])
ex = sfm.explain(R.site_raw, geo)
N.update(sfGeoRtwo=f"{100 * ex.loso_r2.iloc[0]:.0f}", sfGeoTree=f"{ex.coef['tree']:.2f}", sfGeoZo=f"{ex.coef['ln_z0_1km']:.3f}",
         sfGeoCoast=f"{ex.coef['ln1p_coast']:.3f}", sfGeoElev=f"{ex.coef['elev_100m']:.2f}")
co = R.exposure.coefficients()
MACRO = {"b0": "coZero", "b1_tree_near": "coNear", "b2_lnxh": "coLnxh", "b3_lnU": "coLnU", "b_tree_far": "coFar",
         "b_dT": "coDT", "b_lnU_tree": "coLnUTree"}
for k, v in co["speed"].items():
    N[MACRO[k]] = f"{v:.3f}"
N["coSmear"] = f"{co['smearing']:.2f}"
N["coDzero"] = f"{co['direction']['d0']:.1f}"
N["coDone"] = f"{co['direction']['d1_s2a_tree']:.1f}"

with open(GEN / "numbers.tex", "w") as f:
    f.write("% generated by code/scripts/10_paper_tables.py -- do not edit by hand\n")
    for k, v in N.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

# ---- ladder table
P = R.P[R.P.dist <= 80]
steps = [("U0", "Raw SMHI wind at \\SI{10}{m}"), ("U1", "+ height conversion to \\SI{6}{m}"),
         ("U2", "+ two-step roughness conversion"), ("U3", "+ SMHI site factor"), ("U4", "+ roadside exposure model")]
rows = []
for s, lab in steps:
    q = P[f"mae_{s}"].quantile([0.25, 0.5, 0.75]).values
    b = P[f"bias_{s}"].median()
    r = P["r4"].median() if s == "U4" else P["r"].median()
    rows.append(f"{lab} & {q[1]:.2f} & {q[0]:.2f}--{q[2]:.2f} & {100 * b:+.0f}\\,\\% \\\\")
with open(GEN / "tab_ladder.tex", "w") as f:
    f.write("\\begin{tabular}{lccc}\n\\toprule\nStep & MAE median & MAE IQR & bias median \\\\\n & [m\\,s$^{-1}$] & [m\\,s$^{-1}$] & \\\\\n\\midrule\n")
    f.write("\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

# ---- coefficients
B = CV["folds_b"]
names_tex = ["intercept $b_0$", "near trees $T_{100}$", "$\\ln(x/h)$", "$\\ln U_\\mathrm{net}$", "forest fraction $T_{1000}$"]
vals = list(co["speed"].values())
with open(GEN / "tab_coefs.tex", "w") as f:
    f.write("\\begin{tabular}{lccc}\n\\toprule\nTerm & estimate & \\multicolumn{2}{c}{range over 4 time blocks} \\\\\n\\midrule\n")
    for n_, v, lo, hi in zip(names_tex, vals, B.min(0), B.max(0)):
        f.write(f"{n_} & {v:+.3f} & {lo:+.3f} & {hi:+.3f} \\\\\n")
    D = CV["folds_d"]
    f.write(f"direction $d_0$ [deg] & {co['direction']['d0']:+.1f} & {D[:, 0].min():+.1f} & {D[:, 0].max():+.1f} \\\\\n")
    f.write(f"direction $d_1$ [deg] & {co['direction']['d1_s2a_tree']:+.1f} & {D[:, 1].min():+.1f} & {D[:, 1].max():+.1f} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")

# ---- variants
ref = CAND["M8 = M6 − stability (final)"]["mae"]
var = [("M8 = M6 − stability (final)", "Final model"),
       ("M0 baseline (round 6)", "Single tree scale (200 m), $\\ln U\\times T$ interaction, 60 km combination"),
       ("M6 = M5 + 8 sectors, L_smhi 100 m", "Final + stability proxy $\\Delta T$"),
       ("M7 = M6 + cross-road×tree", "Final + $\\Delta T$ + cross-road $\\times$ tree"),
       ("M6 without roughness physics", "Final + $\\Delta T$, without roughness conversion"),
       ("M0 without roughness physics", "Round-6 model without roughness conversion"),
       ("M0 without site factors", "Round-6 model without site factors"),
       ("GBM upper bound (M7 features + Sx, TPI, h_mid)", "Gradient boosting, all features + terrain")]
with open(GEN / "tab_variants.tex", "w") as f:
    f.write("\\begin{tabular}{p{0.40\\textwidth}ccc}\n\\toprule\nModel & mean MAE & median MAE & $\\Delta$ vs final \\\\\n & [m\\,s$^{-1}$] & [m\\,s$^{-1}$] & [m\\,s$^{-1}$] \\\\\n\\midrule\n")
    for k, lab in var:
        m = CAND[k]["mae"]
        dd, ss = paired(m, ref)
        delta = "--" if k.startswith("M8") else f"{dd:+.3f} $\\pm$ {ss:.3f}"
        f.write(f"{lab} & {np.nanmean(m):.3f} & {np.nanmedian(m):.3f} & {delta} \\\\\n")
    f.write("\\bottomrule\n\\end{tabular}\n")
print("\n".join(f"{k} = {v}" for k, v in N.items()))
